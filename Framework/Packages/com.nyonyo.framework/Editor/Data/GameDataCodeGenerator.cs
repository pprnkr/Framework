using System.Collections.Generic;
using System.Text;
using Nyonyo.Framework.Assets;

namespace Nyonyo.Framework.Editor.Data
{
    /// <summary>
    /// 시트마다 행 클래스(<c>{시트}Data</c>)와 테이블 클래스(<c>{시트}Table</c>), 전체를 담는 서비스 클래스(기본 <c>GameData</c>)의 코드를 만듭니다.
    /// </summary>
    /// <remarks>
    /// 모든 클래스는 partial입니다. 게임 쪽에서 같은 이름의 partial 클래스를 만들어 속성이나 함수를 덧붙이고,
    /// 행은 <c>partial void OnLoaded()</c>, 테이블과 서비스는 <c>protected override void OnLoaded()</c>로 로드 후 처리를 넣습니다.
    /// 프레임워크 형식은 게임 쪽 이름과 겹치지 않게 global::로 씁니다.
    /// </remarks>
    internal sealed class GameDataCodeGenerator
    {
        /// <summary>생성 파일 첫 줄에 넣는 표시입니다. 가져오기가 지워도 되는 파일인지 이 표시로 구분합니다.</summary>
        public const string Marker = "// <auto-generated> Nyonyo Framework GameData";

        private const string Framework = "global::Nyonyo.Framework";

        private readonly string _namespace;
        private readonly string _className;
        private readonly LoadType _loadType;
        private readonly string _pathFormat;
        private readonly byte[] _encryptionKey;

        public GameDataCodeGenerator(string ns, string className, LoadType loadType, string pathFormat, byte[] encryptionKey)
        {
            _namespace = ns;
            _className = className;
            _loadType = loadType;
            _pathFormat = pathFormat;
            _encryptionKey = encryptionKey;
        }

        public string GenerateTable(SheetTable table)
        {
            var code = new CodeWriter();
            WriteHeader(code);
            code.Open($"namespace {_namespace}");

            WriteSummary(code, $"{table.Name} 시트의 행 하나입니다. 추가 속성이나 함수는 다른 파일에 partial 클래스로 만드세요.");
            code.Open($"public sealed partial class {table.RowClassName}");
            foreach (var field in table.Fields)
            {
                if (!string.IsNullOrWhiteSpace(field.Comment))
                    WriteSummary(code, field.Comment);
                code.Line($"public {field.Type.TypeName} {field.Name} {{ get; private set; }}");
                code.Line();
            }

            code.Line("/// <summary>값을 다 읽은 뒤 호출됩니다. 게임 쪽 partial 클래스에서 구현하세요.</summary>");
            code.Line("partial void OnLoaded();");
            code.Line();
            code.Open($"internal void Read({Framework}.Data.GameDataReader reader)");
            foreach (var field in table.Fields)
                WriteRead(code, field);
            code.Line("OnLoaded();");
            code.Close();
            code.Close();
            code.Line();

            WriteSummary(code, $"{table.Name} 시트입니다. 키는 {table.Key.Name}입니다.");
            code.Open($"public sealed partial class {table.TableClassName} : {Framework}.Data.DataTable<{table.Key.Type.TypeName}, {table.RowClassName}>");
            code.Line($"public override string Name => \"{table.Name}\";");
            code.Line();
            code.Line($"protected override long SchemaHash => {table.SchemaHash}L;");
            code.Line();
            code.Open($"protected override {table.RowClassName} ReadRow({Framework}.Data.GameDataReader reader)");
            code.Line($"var row = new {table.RowClassName}();");
            code.Line("row.Read(reader);");
            code.Line("return row;");
            code.Close();
            code.Line();
            code.Line($"protected override {table.Key.Type.TypeName} GetKey({table.RowClassName} row) => row.{table.Key.Name};");
            code.Close();

            code.Close();
            return code.ToString();
        }

        public string GenerateRoot(IReadOnlyList<SheetTable> tables)
        {
            var code = new CodeWriter();
            WriteHeader(code);
            code.Open($"namespace {_namespace}");

            WriteSummary(code, "모든 게임 데이터 테이블입니다. Installer에서 서비스로 등록하면 게임 시작 때 모든 테이블을 불러옵니다.");
            code.Line("/// <example><code>");
            code.Line($"/// services.Register(new {_className}(assets));");
            code.Line($"/// var row = {_className}.Instance.시트이름.Get(키);");
            code.Line("/// </code></example>");
            code.Open($"public sealed partial class {_className} : {Framework}.Data.GameDataBase");
            code.Line("// 데이터 파일 암호화 키입니다. 바뀌지 않는 값이라 static readonly로 둡니다.");
            code.Line($"private static readonly byte[] s_encryptionKey = {{ {FormatBytes(_encryptionKey)} }};");
            code.Line();
            code.Line($"private readonly {Framework}.Data.DataTableBase[] _tables;");
            code.Line();
            code.Open($"public {_className}({Framework}.Assets.IAssetLoader loader) : base(loader)");
            var names = new List<string>();
            foreach (var table in tables)
                names.Add(table.Name);
            code.Line($"_tables = new {Framework}.Data.DataTableBase[] {{ {string.Join(", ", names)} }};");
            code.Close();
            code.Line();
            code.Line($"/// <summary>서비스로 등록된 {_className}입니다. <c>Services.Get&lt;{_className}&gt;()</c>와 같습니다.</summary>");
            code.Line($"public static {_className} Instance => {Framework}.Services.Get<{_className}>();");
            code.Line();

            foreach (var table in tables)
            {
                WriteSummary(code, $"{table.Name} 시트입니다. 키는 {table.Key.Name}({table.Key.Type.TypeName})입니다.");
                code.Line($"public {table.TableClassName} {table.Name} {{ get; }} = new {table.TableClassName}();");
                code.Line();
            }

            code.Line($"public override global::System.Collections.Generic.IReadOnlyList<{Framework}.Data.DataTableBase> Tables => _tables;");
            code.Line();
            code.Line($"protected override {Framework}.Assets.LoadType LoadType => {Framework}.Assets.LoadType.{_loadType};");
            code.Line();
            code.Line($"protected override string PathFormat => \"{Escape(_pathFormat)}\";");
            code.Line();
            code.Line("protected override byte[] EncryptionKey => s_encryptionKey;");
            code.Close();

            code.Close();
            return code.ToString();
        }

        private void WriteRead(CodeWriter code, SheetField field)
        {
            var type = field.Type;
            if (type.Kind != SheetValueKind.Enum)
            {
                code.Line($"{field.Name} = reader.{ReaderMethod(type.Kind)}{(type.IsArray ? "Array" : "")}();");
                return;
            }

            if (!type.IsArray)
            {
                code.Line($"{field.Name} = ({type.ElementTypeName})reader.ReadInt();");
                return;
            }

            code.Open("");
            code.Line($"var values = new {type.ElementTypeName}[reader.ReadCount()];");
            code.Line("for (var i = 0; i < values.Length; i++)");
            code.Line($"    values[i] = ({type.ElementTypeName})reader.ReadInt();");
            code.Line($"{field.Name} = values;");
            code.Close();
        }

        private string ReaderMethod(SheetValueKind kind)
        {
            if (kind == SheetValueKind.Int)
                return "ReadInt";
            if (kind == SheetValueKind.Long)
                return "ReadLong";
            if (kind == SheetValueKind.Float)
                return "ReadFloat";
            if (kind == SheetValueKind.Double)
                return "ReadDouble";
            if (kind == SheetValueKind.Bool)
                return "ReadBool";
            return "ReadString";
        }

        private void WriteHeader(CodeWriter code)
        {
            code.Line(Marker);
            code.Line("// 구글 스프레드시트에서 가져올 때마다 다시 만들어지는 파일입니다. 직접 고치지 마세요.");
            code.Line("// 코드를 덧붙이려면 다른 파일에 같은 이름의 partial 클래스를 만드세요.");
            code.Line("// </auto-generated>");
            code.Line();
        }

        private void WriteSummary(CodeWriter code, string text)
        {
            var singleLine = text.Replace("\r", " ").Replace("\n", " ");
            code.Line($"/// <summary>{EscapeXml(singleLine)}</summary>");
        }

        private string FormatBytes(byte[] bytes)
        {
            var text = new StringBuilder();
            for (var i = 0; i < bytes.Length; i++)
            {
                if (i > 0)
                    text.Append(", ");
                text.Append("0x").Append(bytes[i].ToString("X2"));
            }
            return text.ToString();
        }

        private string EscapeXml(string text) => text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");

        private string Escape(string text) => text.Replace("\\", "\\\\").Replace("\"", "\\\"");

        /// <summary>들여쓰기를 맞춰 줄을 쌓습니다. 줄바꿈은 \n입니다.</summary>
        private sealed class CodeWriter
        {
            private readonly StringBuilder _text = new();
            private int _indent;

            public void Line(string line = "")
            {
                if (line.Length > 0)
                    _text.Append(' ', _indent * 4).Append(line);
                _text.Append('\n');
            }

            /// <summary><paramref name="header"/> 줄과 여는 중괄호를 쓰고 들여쓰기를 늘립니다. 빈 문자열이면 중괄호만 엽니다.</summary>
            public void Open(string header)
            {
                if (header.Length > 0)
                    Line(header);
                Line("{");
                _indent++;
            }

            public void Close()
            {
                _indent--;
                Line("}");
            }

            public override string ToString() => _text.ToString();
        }
    }
}
